public sealed class ReleaseWorkspace(
    IPipelineStateManager stateManager,
    IGitService gitService,
    BumpVersionStep bumpStep,
    MergeAndPublishStep publishStep,
    IAiCommitAssistant aiAssistant,
    ProjectContext projectContext,
    IVersionEngine versionEngine,
    IProjectDiscoveryService projectDiscovery,
    IEnvironmentInfoProvider infoProvider) : ITuiWorkspace
{
    private readonly IPipelineStateManager _stateManager = stateManager;
    private readonly IGitService _gitService = gitService;
    private readonly BumpVersionStep _bumpStep = bumpStep;
    private readonly MergeAndPublishStep _publishStep = publishStep;
    private readonly IAiCommitAssistant _aiAssistant = aiAssistant;
    private readonly ProjectContext _projectContext = projectContext;
    private readonly IVersionEngine _versionEngine = versionEngine;
    private readonly IProjectDiscoveryService _projectDiscovery = projectDiscovery;
    private readonly IEnvironmentInfoProvider _infoProvider = infoProvider;

    public string Name => "Release Master & Recovery";
    public string Description => "End-to-End release pipeline with AI Changelog and rollback capability";

    private record MenuOption(VersionBumpStrategy? Strategy);
    private record StrategyMenuChoice(VersionBumpStrategy? Strategy, string Display);

    private string AppendSignatureFooter(string releaseNotes, string modelId)
    {
        string appVersion = _infoProvider.GetApplicationVersion();
        var footer = new StringBuilder();
        footer.AppendLine();
        footer.AppendLine();
        footer.AppendLine("---");
        footer.AppendLine("<p align=\"right\">");
        footer.Append($"<sub>Generated by <b>Instancium.Publisher</b> v{appVersion} • Model: <code>{modelId}</code></sub>");
        footer.AppendLine();
        footer.Append("</p>");
        return releaseNotes + footer.ToString();
    }

    public async Task ExecuteAsync(CancellationToken ct = default)
    {
        var activeContext = await _stateManager.LoadAsync();
        if (activeContext != null && activeContext.CurrentStep > 0)
        {
            AnsiConsole.MarkupLine($"[yellow]Interrupted release detected at step {activeContext.CurrentStep}.[/]");
            AnsiConsole.WriteLine();
            NavigationBreadcrumbsBar.Render("Projects", _projectContext.Name, "Release", "Recovery Dispatcher");

            var choice = AnsiConsole.Prompt(
                new SelectionPrompt<string>()
                    .HighlightStyle(new Style(Color.Cyan, decoration: Decoration.Bold))
                    .AddChoices("Resume", "Rollback", "Start Fresh"));

            if (choice == "Rollback")
            {
                await ExecuteDestructiveRollbackAsync(activeContext, ct);
                return;
            }
            if (choice == "Start Fresh")
            {
                await ExecuteDestructiveRollbackAsync(activeContext, ct);
                activeContext = null;
            }
        }

        activeContext ??= new PipelineContext { CurrentStep = 1 };

        try
        {
            if (activeContext.CurrentStep > 1 && !string.IsNullOrWhiteSpace(activeContext.ReleaseBranch))
            {
                string currentBranch = await _gitService.GetCurrentBranchAsync(ct);
                if (!string.Equals(currentBranch, activeContext.ReleaseBranch, StringComparison.OrdinalIgnoreCase))
                {
                    AnsiConsole.MarkupLine($"[dim]Restoring context: checking out {Markup.Escape(activeContext.ReleaseBranch)}...[/]");
                    await CheckoutReleaseBranchAsync(activeContext.ReleaseBranch, ct);
                }
            }

            if (activeContext.CurrentStep <= 1)
            {
                string repositoryRoot = await _gitService.GetRepositoryRootAsync(ct);
                IReadOnlyList<string> projectPaths = await _projectDiscovery.DiscoverProjectFilesAsync(repositoryRoot, ct);

                if (projectPaths.Count == 0)
                {
                    throw new FileNotFoundException($"No .csproj project files found under repository root: {repositoryRoot}");
                }

                IReadOnlyList<ProjectVersionSnapshot> snapshots = await _versionEngine.ReadProjectVersionsAsync(projectPaths, ct);
                SemanticVersion? repositoryVersion = RepositoryVersionPolicy.TryResolveCurrentVersion(snapshots);

                RenderContextPanel(repositoryVersion, snapshots, repositoryRoot);

                VersionBumpStrategy? strategy = null;
                string? customVersion = null;

                if (activeContext.NewVersion is null)
                {
                    (strategy, customVersion) = PromptVersionStrategy(repositoryVersion);
                    if (strategy is null)
                    {
                        return;
                    }

                    activeContext.CurrentVersion = repositoryVersion;
                    activeContext.NewVersion = repositoryVersion is null
                        ? RepositoryVersionPolicy.CalculateInitialVersion(strategy.Value, customVersionString: customVersion)
                        : _versionEngine.CalculateNext(repositoryVersion, strategy.Value, customVersionString: customVersion);
                }
                else
                {
                    AnsiConsole.MarkupLine(
                        $"[yellow]Resuming interrupted release: planned version v{activeContext.NewVersion} will be applied to all {projectPaths.Count} project(s).[/]");
                }

                if (string.IsNullOrWhiteSpace(activeContext.SourceBranch))
                {
                    activeContext.SourceBranch = await _gitService.GetCurrentBranchAsync(ct);
                }

                activeContext.ReleaseBranch = $"release-prep/v{activeContext.NewVersion}";
                await CheckoutReleaseBranchAsync(activeContext.ReleaseBranch, ct);

                await TuiProgressReporter.RunWithLiveStatusAsync(
                    "Bumping repository version...",
                    async () => await _bumpStep.ExecuteAsync(activeContext, snapshots, strategy, customVersion, ct),
                    ct);

                AnsiConsole.MarkupLine($"[green]Repository version set to v{activeContext.NewVersion} across {projectPaths.Count} project(s).[/]");
                activeContext.CurrentStep = 2;
                await _stateManager.SaveAsync(activeContext);
            }

            if (activeContext.CurrentStep <= 2)
            {
                string lastTag = string.Empty;
                try { lastTag = await _gitService.GetLatestTagAsync(ct); } catch { }

                string rangeDescription = string.IsNullOrWhiteSpace(lastTag)
                    ? "last 20 commits (no tags found in repository)"
                    : $"{lastTag}..HEAD";

                AnsiConsole.MarkupLine($"\n[dim]Changelog commit range: {Markup.Escape(rangeDescription)}[/]");
                string gitLog = await _gitService.GetCommitLogAsync(lastTag, ct);

                var fullNotesBuilder = new StringBuilder();
                await using var enumerator = _aiAssistant.StreamReleaseNotesAsync(gitLog, ct).GetAsyncEnumerator(ct);
                bool hasData = false;

                await TuiProgressReporter.RunWithLiveStatusAsync(
                    "Analyzing commit history...",
                    async () => { hasData = await enumerator.MoveNextAsync(); },
                    ct);

                AnsiConsole.MarkupLine("\n[green]Generating Release Notes (AI Changelog):[/]");

                if (hasData)
                {
                    fullNotesBuilder.Append(enumerator.Current);
                    await AnsiConsole.Live(new Panel("[dim]Initializing stream...[/]"))
                        .AutoClear(false)
                        .StartAsync(async ctx =>
                        {
                            while (true)
                            {
                                string safeText = Markup.Escape(fullNotesBuilder.ToString());
                                ctx.UpdateTarget(
                                    new Panel($"[silver]{safeText}[/]")
                                        .Header("[cyan]Live AI Stream[/]")
                                        .BorderColor(Color.Grey)
                                        .Expand());

                                if (!await enumerator.MoveNextAsync()) break;
                                fullNotesBuilder.Append(enumerator.Current);
                            }

                            ctx.UpdateTarget(ParseMarkdownToSpectre(fullNotesBuilder.ToString()));
                        });
                }

                AnsiConsole.WriteLine();
                string rawNotes = fullNotesBuilder.ToString().Trim();
                string sanitizedNotes = SanitizeReleaseNotes(rawNotes);
                string modelId = await _infoProvider.GetActiveModelIdAsync(ct);
                activeContext.ReleaseNotes = AppendSignatureFooter(sanitizedNotes, modelId);

                AnsiConsole.WriteLine();
                NavigationBreadcrumbsBar.Render("Projects", _projectContext.Name, "Release", "Confirm Publication");

                var approveChoice = AnsiConsole.Prompt(
                    new SelectionPrompt<string>()
                        .HighlightStyle(new Style(Color.Cyan, decoration: Decoration.Bold))
                        .AddChoices("Approve and Publish", "Abort (Keep state)", "Rollback (Destroy branch)"));

                if (approveChoice == "Abort (Keep state)") return;
                if (approveChoice == "Rollback (Destroy branch)")
                {
                    await ExecuteDestructiveRollbackAsync(activeContext, ct);
                    return;
                }

                activeContext.CurrentStep = 3;
                await _stateManager.SaveAsync(activeContext);
            }

            if (activeContext.CurrentStep <= 3)
            {
                await TuiProgressReporter.RunWithLiveStatusAsync(
                    "Merging and publishing release to GitHub...",
                    async () =>
                    {
                        if (await _gitService.HasUncommittedChangesAsync(ct))
                        {
                            await _gitService.AddAllAsync(ct);
                            await _gitService.CommitAsync($"chore(release): prepare version v{activeContext.NewVersion}", ct);
                        }

                        await _publishStep.ExecuteAsync(activeContext, "main", ct);
                        await _gitService.CheckoutBranchAsync(activeContext.SourceBranch, false, ct);
                        await _gitService.DeleteLocalBranchAsync(activeContext.ReleaseBranch, ct);
                        await _gitService.DeleteRemoteBranchAsync(activeContext.ReleaseBranch, ct);
                    },
                    ct);

                AnsiConsole.MarkupLine($"\n[bold green]Release v{activeContext.NewVersion} published successfully![/]");
                await _stateManager.RollbackAsync();
                AnsiConsole.MarkupLine("\n[dim]Press ANY KEY to return to main menu...[/]");
                Console.ReadKey(intercept: true);
            }
        }
        catch (ProjectFileParseException ex)
        {
            AnsiConsole.MarkupLine($"\n[bold red]Release Pipeline Faulted:[/] {Markup.Escape(ex.Message)}");
            AnsiConsole.MarkupLine("[yellow]Fix the file above: resolve merge conflicts, repair encoding, or restore it via 'git checkout -- <file>'. Then choose Resume.[/]");
            await _stateManager.SaveAsync(activeContext);
            AnsiConsole.MarkupLine("\n[dim]Press ANY KEY to return to main menu...[/]");
            Console.ReadKey(intercept: true);
        }
        catch (Exception ex)
        {
            AnsiConsole.MarkupLine($"\n[bold red]Release Pipeline Faulted:[/] {Markup.Escape(ex.Message)}");
            AnsiConsole.MarkupLine("[yellow]Pipeline state has been saved. If a merge failed, it was automatically aborted to protect your project files. You can safely choose 'Resume' after investigating the issue.[/]");
            await _stateManager.SaveAsync(activeContext);
            AnsiConsole.MarkupLine("\n[dim]Press ANY KEY to return to main menu...[/]");
            Console.ReadKey(intercept: true);
        }
    }

    private (VersionBumpStrategy? Strategy, string? CustomVersion) PromptVersionStrategy(SemanticVersion? currentVersion)
    {
        AnsiConsole.WriteLine();
        NavigationBreadcrumbsBar.Render("Projects", _projectContext.Name, "Release", "Select Bump Strategy");

        var rawOptions = Enum.GetValues<VersionBumpStrategy>()
            .Select(s => new MenuOption(s))
            .ToList();
        rawOptions.Add(new MenuOption(null));

        var formattedLookup = TwoColumnMenuFormatter.FormatRows(
            rawOptions,
            opt => GetStrategyTitle(opt.Strategy),
            opt => GetStrategyPreview(opt.Strategy, currentVersion));

        var choices = rawOptions
            .Select(opt => new StrategyMenuChoice(opt.Strategy, formattedLookup[opt]))
            .ToList();

        StrategyMenuChoice selectedChoice = AnsiConsole.Prompt(
            new SelectionPrompt<StrategyMenuChoice>()
                .PageSize(12)
                .HighlightStyle(new Style(Color.Cyan, decoration: Decoration.Bold))
                .AddChoices(choices)
                .UseConverter(opt => opt.Display));

        if (selectedChoice.Strategy is null)
        {
            return (null, null);
        }

        if (selectedChoice.Strategy != VersionBumpStrategy.Custom)
        {
            return (selectedChoice.Strategy, null);
        }

        while (true)
        {
            string rawVersion = AnsiConsole.Prompt(
                new TextPrompt<string>("Enter custom version (SemVer 2.0, empty to cancel):")
                    .AllowEmpty());

            if (string.IsNullOrWhiteSpace(rawVersion))
            {
                return (null, null);
            }

            try
            {
                return (VersionBumpStrategy.Custom, _versionEngine.Parse(rawVersion).ToString());
            }
            catch (FormatException)
            {
                AnsiConsole.MarkupLine($"[red]'{Markup.Escape(rawVersion)}' is not a valid SemVer 2.0 string. Try again.[/]");
            }
        }
    }

    private static string GetStrategyTitle(VersionBumpStrategy? strategy) => strategy switch
    {
        null => "Return to Menu",
        VersionBumpStrategy.Patch => "Patch",
        VersionBumpStrategy.Minor => "Minor",
        VersionBumpStrategy.Major => "Major",
        VersionBumpStrategy.NewPreReleasePatch => "Pre-Release Patch",
        VersionBumpStrategy.NewPreReleaseMinor => "Pre-Release Minor",
        VersionBumpStrategy.NewPreReleaseMajor => "Pre-Release Major",
        VersionBumpStrategy.PreReleaseIteration => "Pre-Release Iteration",
        VersionBumpStrategy.PromoteToRelease => "Promote To Release",
        VersionBumpStrategy.Custom => "Custom",
        _ => strategy.ToString() ?? string.Empty
    };

    private string GetStrategyPreview(VersionBumpStrategy? strategy, SemanticVersion? currentVersion)
    {
        if (!strategy.HasValue)
        {
            return "Exit to Main CLI";
        }

        SemanticVersion baseline = currentVersion ?? RepositoryVersionPolicy.InitialVersion;

        return strategy.Value switch
        {
            VersionBumpStrategy.Patch => $"{baseline} → {_versionEngine.CalculateNext(baseline, VersionBumpStrategy.Patch)}",
            VersionBumpStrategy.Minor => $"{baseline} → {_versionEngine.CalculateNext(baseline, VersionBumpStrategy.Minor)}",
            VersionBumpStrategy.Major => $"{baseline} → {_versionEngine.CalculateNext(baseline, VersionBumpStrategy.Major)}",
            VersionBumpStrategy.NewPreReleasePatch => $"{baseline} → {_versionEngine.CalculateNext(baseline, VersionBumpStrategy.NewPreReleasePatch)}",
            VersionBumpStrategy.NewPreReleaseMinor => $"{baseline} → {_versionEngine.CalculateNext(baseline, VersionBumpStrategy.NewPreReleaseMinor)}",
            VersionBumpStrategy.NewPreReleaseMajor => $"{baseline} → {_versionEngine.CalculateNext(baseline, VersionBumpStrategy.NewPreReleaseMajor)}",
            VersionBumpStrategy.PreReleaseIteration => baseline.IsPreRelease
                ? $"{baseline} → {_versionEngine.CalculateNext(baseline, VersionBumpStrategy.PreReleaseIteration)}"
                : $"{baseline} → {baseline.Major}.{baseline.Minor}.{baseline.Patch + 1}-rc.1",
            VersionBumpStrategy.PromoteToRelease => baseline.IsPreRelease
                ? $"{baseline} → {_versionEngine.CalculateNext(baseline, VersionBumpStrategy.PromoteToRelease)}"
                : "No active pre-release tag",
            VersionBumpStrategy.Custom => "User defined SemVer 2.0",
            _ => string.Empty
        };
    }

    private async Task CheckoutReleaseBranchAsync(string branchName, CancellationToken ct)
    {
        try
        {
            await _gitService.CheckoutBranchAsync(branchName, createNew: true, ct);
        }
        catch (InvalidOperationException ex) when (ex.Message.Contains("already exists", StringComparison.OrdinalIgnoreCase))
        {
            AnsiConsole.MarkupLine($"[yellow]Release branch '{Markup.Escape(branchName)}' already exists. Reusing it.[/]");
            await _gitService.CheckoutBranchAsync(branchName, createNew: false, ct);
        }
    }

    private static string SanitizeReleaseNotes(string rawNotes)
    {
        if (string.IsNullOrWhiteSpace(rawNotes))
        {
            return string.Empty;
        }

        var lines = rawNotes.Replace("\r\n", "\n").Split('\n')
            .Where(l => !l.StartsWith("```"))
            .Select(l => l.TrimEnd())
            .ToList();

        return string.Join(Environment.NewLine, lines).Trim();
    }

    private void RenderContextPanel(
        SemanticVersion? repositoryVersion,
        IReadOnlyList<ProjectVersionSnapshot> snapshots,
        string repositoryRoot)
    {
        int divergentProjects = RepositoryVersionPolicy.CountDivergentProjects(snapshots, repositoryVersion);
        string versionText = repositoryVersion is null
            ? "[yellow]none declared (initial baseline 1.0.0)[/]"
            : $"[bold green]{repositoryVersion}[/]";

        string divergentText = divergentProjects == 0
            ? "[dim green]none[/]"
            : $"[yellow]{divergentProjects} (will be aligned on release)[/]";

        var panel = new Panel(
            $"Active Project:      [bold white]{Markup.Escape(_projectContext.Name)}[/]\n" +
            $"Repository Root:     [dim]{Markup.Escape(repositoryRoot)}[/]\n" +
            $"Projects to Version: [bold white]{snapshots.Count}[/]\n" +
            $"Repository Version:  {versionText}\n" +
            $"Divergent Projects:  {divergentText}")
            .Header("[yellow]Release Context[/]")
            .BorderColor(Color.Grey)
            .RoundedBorder()
            .Expand();

        AnsiConsole.Write(panel);
        AnsiConsole.WriteLine();
    }

    private async Task ExecuteDestructiveRollbackAsync(PipelineContext context, CancellationToken ct)
    {
        AnsiConsole.MarkupLine("[red]Executing safe rollback...[/]");
        try
        {
            string currentBranch = await _gitService.GetCurrentBranchAsync(ct);

            // Безопасность: Делаем жесткий сброс файлов ТОЛЬКО если находимся в изолированной ветке релиза
            if (!string.IsNullOrEmpty(context.ReleaseBranch) &&
                string.Equals(currentBranch, context.ReleaseBranch, StringComparison.OrdinalIgnoreCase))
            {
                await _gitService.RestoreAllAsync(ct);

                if (!string.IsNullOrEmpty(context.SourceBranch))
                {
                    await _gitService.CheckoutBranchAsync(context.SourceBranch, false, ct);
                }
            }

            if (!string.IsNullOrEmpty(context.ReleaseBranch))
            {
                await _gitService.DeleteLocalBranchAsync(context.ReleaseBranch, ct);
                await _gitService.DeleteRemoteBranchAsync(context.ReleaseBranch, ct);
            }

            await _stateManager.RollbackAsync();
            AnsiConsole.MarkupLine("[green]Release branch removed and pipeline state reset safely.[/]");
        }
        catch (Exception ex)
        {
            AnsiConsole.MarkupLine($"[bold red]Rollback FATAL error:[/] {Spectre.Console.Markup.Escape(ex.Message)}");
            AnsiConsole.MarkupLine("[yellow]Pipeline state retained. Manual Git fix may be required before retrying Rollback.[/]");
            throw;
        }
    }

    private static Spectre.Console.Rendering.IRenderable ParseMarkdownToSpectre(string markdown)
    {
        var lines = markdown.Split(['\r', '\n'], StringSplitOptions.RemoveEmptyEntries);
        var summaryBuilder = new StringBuilder();
        Table? table = null;

        foreach (var line in lines)
        {
            string trimLine = line.Trim();
            if (trimLine.StartsWith(">"))
            {
                string content = trimLine[1..].Trim();
                content = content.Replace("**Executive Summary**", "[bold cyan]Executive Summary[/]");
                summaryBuilder.AppendLine(content);
            }
            else if (trimLine.StartsWith("|"))
            {
                var cells = trimLine.Split('|', StringSplitOptions.RemoveEmptyEntries).Select(c => c.Trim()).ToArray();
                if (cells.Length == 0) continue;
                if (cells[0].Contains("---") || (cells.Length > 1 && cells[1].Contains("---"))) continue;

                if (table == null)
                {
                    table = new Table().Expand().Border(TableBorder.Rounded).BorderColor(Color.Grey);
                    foreach (var header in cells)
                    {
                        table.AddColumn($"[bold silver]{Markup.Escape(header)}[/]");
                    }
                }
                else
                {
                    if (cells.Length == table.Columns.Count)
                    {
                        var finalCells = cells.Select(c =>
                        {
                            string escaped = Markup.Escape(c);
                            return System.Text.RegularExpressions.Regex.Replace(escaped, @"\`(.*?)\`", "[cyan]$1[/]");
                        }).ToArray();
                        table.AddRow(finalCells);
                    }
                }
            }
        }

        var elements = new List<Spectre.Console.Rendering.IRenderable>();
        if (summaryBuilder.Length > 0)
        {
            elements.Add(new Panel($"[silver]{summaryBuilder.ToString().Trim()}[/]")
                .Header("[bold green]Release Impact[/]")
                .BorderColor(Color.Green)
                .RoundedBorder()
                .Expand());
            elements.Add(new Text(""));
        }

        if (table != null)
        {
            elements.Add(table);
        }

        if (elements.Count == 0)
        {
            return new Markup($"[silver]{Markup.Escape(markdown)}[/]");
        }

        return new Rows(elements);
    }
}